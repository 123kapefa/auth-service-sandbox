/**
 * Поле «Телефон или почта». Логин-телефон хранится цифрами без «+» (79990000001), а человек видит и вводит его
 * привычно: +7 (999) 000-00-01. Окончательно номер приводит к логину сервер (8XXX → 7XXX, 10 цифр → 7XXX).
 */

/** Похоже на номер: только цифры, «+», пробелы, скобки и дефисы, и есть хотя бы одна цифра. */
const PHONE_LIKE = /^[+\d\s()-]*\d[+\d\s()-]*$/;

/** Начали вводить номер — перед ним «+»; стёрли номер целиком — без одинокого «+»; почта — как есть. */
export function withPlus(value: string): string {
  if (/^\d/.test(value)) {
    return `+${value}`;
  }

  return value === "+" ? "" : value;
}

/** Перед отправкой: номер — только цифры, почта и прочее — как есть. */
export function toLogin(value: string): string {
  return PHONE_LIKE.test(value) ? value.replace(/\D/g, "") : value;
}
